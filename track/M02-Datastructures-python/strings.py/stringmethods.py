# Inbuilt string Methods -single Program
s = "  kodnest Technogies 123  "
print("Original string:", s) #   kodnest Technogies 123

# Case conversion methods
print("upper()", s.upper()) #    kodnest Technogies 123  
print("lower()", s.lower()) #    kodnest Technogies 123  
print("title()", s.title()) #    Kodnest Technogies 123  
print("swapcase()", s.swapcase()) #   KODNEST TECHONOGIES 123 
#searching & counting
print("find('Tech'):", s.find("Tech"))

